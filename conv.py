#!/usr/bin/env python3
import argparse, csv, sys
from pathlib import Path

def s(v): return "'" + v.replace("'", "''") + "'"
def num(v, field):
    v=v.strip()
    try: float(v)
    except ValueError: raise ValueError(f"{field} must be a number: {v!r}")
    return v

def main():
    p=argparse.ArgumentParser()
    p.add_argument('input', type=Path); p.add_argument('output', type=Path)
    a=p.parse_args()
    with a.input.open(encoding='utf-8-sig', newline='') as f:
        r=csv.DictReader(f); required={'name','address','latitude','longitude','url'}
        if not r.fieldnames: print('ERROR: CSV header is missing.',file=sys.stderr); return 1
        missing=required-set(r.fieldnames)
        if missing: print(f"ERROR: missing CSV columns: {', '.join(sorted(missing))}",file=sys.stderr); return 1
        out=[]
        for line,row in enumerate(r,2):
            try:
                name=row['name'].strip(); address=row['address'].strip(); url=row['url'].strip()
                if not name: raise ValueError('name is empty')
                if not url: raise ValueError('url is empty')
                lat=num(row['latitude'],'latitude'); lon=num(row['longitude'],'longitude')
                out.append("INSERT INTO halls (name,address,latitude,longitude,url) VALUES "
                    f"({s(name)},{s(address)},{lat},{lon},{s(url)}) "
                    "ON CONFLICT(url) DO UPDATE SET name=excluded.name,address=excluded.address,"
                    "latitude=excluded.latitude,longitude=excluded.longitude;")
            except (KeyError,ValueError) as e:
                print(f'ERROR: line {line}: {e}',file=sys.stderr); return 1
    with a.output.open('w',encoding='utf-8',newline='\n') as f:
        f.write('-- Generated by conv.py (D1はBEGIN/COMMITを受け付けないため省略)\n')
        f.write('\n'.join(out)); f.write('\n')
    print(f'Generated: {a.output}\nRows:      {len(out)}')
    print('次に検索用JSONも更新してください: python3 tools/build_halls_json.py', a.output, 'worker/halls.json')

if __name__=='__main__': raise SystemExit(main())

